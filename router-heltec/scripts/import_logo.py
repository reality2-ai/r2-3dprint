#!/usr/bin/env python3
"""Extract the supplied sticker's tree vector for the Heltec lid and inlay.

Standard library only. Preserve the source cubic curves; never trace a bitmap
or smooth/refit the artwork. Flatten only for OpenSCAD's polygon representation.
"""
import hashlib
import json
import math
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'mariko-sticker.svg'
WIDTH = 80.0
CHORD_ERROR = 0.005  # mm at the nominal 80 mm width


def midpoint(a, b):
    return tuple((x+y)/2 for x,y in zip(a,b))


def nearest(p, a, b):
    dx,dy = b[0]-a[0],b[1]-a[1]
    t = max(0,min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy))) if dx or dy else 0
    return a[0]+t*dx,a[1]+t*dy


def distance(a, b):
    return math.hypot(a[0]-b[0],a[1]-b[1])


def flatten(a, b, c, d, tolerance):
    # Convex-hull bound: the entire cubic lies within this distance of its
    # chord. Subdivide with de Casteljau without changing the source curve.
    if max(distance(p,nearest(p,a,d)) for p in (b,c)) <= tolerance:
        return [a,d]
    ab,bc,cd = midpoint(a,b),midpoint(b,c),midpoint(c,d)
    abc,bcd = midpoint(ab,bc),midpoint(bc,cd)
    m = midpoint(abc,bcd)
    return flatten(a,ab,abc,m,tolerance)[:-1]+flatten(m,bcd,cd,d,tolerance)


def parse_tree():
    root = ET.parse(SOURCE).getroot()
    tree = next(p for p in root.iter() if p.get('id') == 'tree')
    assert not tree.get('transform'), 'Update extraction for transformed source artwork'
    data = tree.attrib['d']
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?',data)
    i = 0; paths = []; path = None
    while i < len(tokens):
        cmd=tokens[i];i+=1
        if cmd=='M':
            p=(float(tokens[i]),float(tokens[i+1]));i+=2
            start=p;path=[];paths.append(path)
        elif cmd=='C':
            points=[tuple(map(float,tokens[j:j+2])) for j in range(i,i+6,2)]
            i+=6;path.append((p,*points));p=points[-1]
        elif cmd=='Z':
            assert distance(p,start)<1e-8, 'Source contour must close exactly'
        else:
            raise ValueError(f'Unsupported SVG command {cmd}; do not silently discard artwork')
    assert len(paths)==2, 'Expected outer tree and root cutout only'
    return data,paths


def cubic_bounds(paths):
    # Include exact cubic extrema so size/centring do not depend on tessellation.
    points=[]
    for path in paths:
        for a,b,c,d in path:
            ts={0.0,1.0}
            for axis in (0,1):
                aa=-a[axis]+3*b[axis]-3*c[axis]+d[axis]
                bb=2*(a[axis]-2*b[axis]+c[axis])
                cc=b[axis]-a[axis]
                if abs(aa)<1e-12:
                    roots=[-cc/bb] if abs(bb)>1e-12 else []
                else:
                    disc=bb*bb-4*aa*cc
                    roots=[(-bb+sign*math.sqrt(disc))/(2*aa) for sign in (-1,1)] if disc>=0 else []
                ts.update(t for t in roots if 0<t<1)
            for t in ts:
                points.append(tuple((1-t)**3*a[k]+3*(1-t)**2*t*b[k]+3*(1-t)*t*t*c[k]+t**3*d[k] for k in (0,1)))
    return [[min(p[k] for p in points),max(p[k] for p in points)] for k in (0,1)]


def main():
    data,paths=parse_tree()
    bounds=cubic_bounds(paths)
    scale=WIDTH/(bounds[0][1]-bounds[0][0])
    centre=[sum(b)/2 for b in bounds]
    # SVG Y points down. CAD Y points toward the back of the lid: reflect Y
    # once here to retain the original readable orientation, with no X mirror.
    convert=lambda p:((p[0]-centre[0])*scale,(centre[1]-p[1])*scale)
    contours=[]
    for path in paths:
        points=[convert(p) for segment in path for p in flatten(*segment,CHORD_ERROR/scale)[:-1]]
        clean=[]
        for p in points:
            if not clean or distance(p,clean[-1])>0.0001: clean.append(p)
        if distance(clean[0],clean[-1])<=0.0001:clean.pop()
        contours.append(clean)
    outer=contours[0]
    targets=[(0,45),(-40,3),(40,3),(-24.7,-34.7),(24.5,-34.5),(0,-45)]
    grip=[]
    for p in targets:
        candidates=[nearest(p,a,b) for a,b in zip(outer,outer[1:]+outer[:1])]
        grip.append(min(candidates,key=lambda q:distance(p,q)))
    flat=[];indices=[]
    for ring in contours:
        indices.append(list(range(len(flat),len(flat)+len(ring))))
        flat.extend(ring)
    fmt=lambda p:f'[{p[0]:.6f},{p[1]:.6f}]'
    output='''// Generated by scripts/import_logo.py from ../../mariko-sticker.svg, id="tree".
// Original cubic curves, sampled to <=0.005 mm chord error at 80 mm width.
// No bitmap trace or curve refitting. Do not hand-edit this generated file.
'''
    output+='vector_tree_points = [\n'+',\n'.join('  '+fmt(p) for p in flat)+'\n];\n'
    output+='vector_tree_paths = '+json.dumps(indices,separators=(',',':'))+';\n'
    output+='vector_tree_grip = ['+','.join(fmt(p) for p in grip)+'];\n'
    output+='''module mariko_logo_vector(w=80) {
    scale(w/80) polygon(points=vector_tree_points,paths=vector_tree_paths);
}
function vector_logo_grip_points(w=80) = [for(p=vector_tree_grip) p*w/80];
'''
    (ROOT/'src/mariko_logo_vector.scad').write_text(output)
    # Preserve the original path text verbatim in an independently viewable,
    # tree-only SVG. ViewBox crops away sticker lettering, ring and cutline.
    height=(bounds[1][1]-bounds[1][0])*scale
    viewbox=f'{bounds[0][0]:.9f} {bounds[1][0]:.9f} {WIDTH/scale:.9f} {height/scale:.9f}'
    svg=f'''<svg xmlns="http://www.w3.org/2000/svg" width="80mm" height="{height:.9f}mm" viewBox="{viewbox}">
<title>Original Mariko tree from mariko-sticker.svg</title>
<path id="tree" fill="#10783e" fill-rule="evenodd" d="{data}"/>
</svg>
'''
    (ROOT/'references/mariko-tree.svg').write_text(svg)
    metadata={'source':'../../mariko-sticker.svg','source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
              'element_id':'tree','method':'Original SVG cubic curves; adaptive de Casteljau tessellation without refitting',
              'width_mm':WIDTH,'height_mm':height,'maximum_chord_error_mm':CHORD_ERROR,
              'source_cubic_segments':[len(p) for p in paths], 'contour_vertices':[len(p) for p in contours],
              'source_bounds':bounds,'source_centre':centre,'source_scale_to_mm':scale,
              'bounds_mm':[[-WIDTH/2,WIDTH/2],[-height/2,height/2]],'grip_centres_mm':grip}
    (ROOT/'references/logo-source.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(json.dumps(metadata,indent=2))


if __name__=='__main__':
    main()
